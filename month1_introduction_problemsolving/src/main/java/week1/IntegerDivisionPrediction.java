public class IntegerDivisionPrediction {
    public static void main(String[] args) {
        System.out.println("7 / 3 = " + (7 / 3));
        System.out.println("7 % 3 = " + (7 % 3));
        System.out.println("7 / 3.0 = " + (7 / 3.0));
        System.out.println("(double)(7 / 3) = " + (double)(7 / 3));
    }
}
